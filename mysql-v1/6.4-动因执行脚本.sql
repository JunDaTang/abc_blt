-- ============================================================
-- 文件名: 6.4-动因执行脚本.sql
-- 说明: 调用存储过程生成四级分摊的动因数据
--       动因是成本分摊的"权重"，决定了成本在各维度间的分配比例
--       执行顺序：先生成业务量 → 再生成四级动因（RR → RA → AA → AO）
-- 执行顺序: 第4步（动因计算），在业务数据（4.4）和动因配置（6.2）之后、
--           分摊执行（7.3/8.3）之前执行
-- ============================================================

-- MySQL 版本
-- 源文件: 6.4-动因执行脚本.sql
USE abc_blt;

-- 第1步：生成运单操作业务量
-- 根据运单数据计算每个运单在各操作环节（收件、派件、运输、装卸、中转）的业务量
-- 写入 ABC_BSL_OP_WAYBILL，是后续动因计算的基础
CALL p_abc_bsl_op_waybill('2019-05-01 00:00:00', '2019-06-01 00:00:00');

-- 第2步：生成 RR 动因（资源→资源）
-- 计算各营业点的收派票数（RR002），用于公共资源在功能中心间的分摊
-- 结果写入 ABC_FCT_RR_DRIV
CALL p_abc_fct_rr_driv('2019-06-01 00:00:00');

-- 第3步：生成 RA 动因（资源→作业）
-- 计算线路里程（RA002）、装卸中转票数（RA003）等，用于资源成本分摊到作业
-- 结果写入 ABC_FCT_RA_DRIV
CALL p_abc_fct_ra_driv('2019-06-01 00:00:00');

-- 第4步：生成 AA 动因（作业→作业）
-- 计算车辆装载重量（AA002）、整包单件装卸票数（AA003）、整包单件中转票数（AA004）
-- 用于辅助作业间的成本再分摊
-- 结果写入 ABC_FCT_AA_DRIV
CALL p_abc_fct_aa_driv('2019-06-01 00:00:00');

-- 第5步：生成 AO 动因（作业→运单）
-- 计算各作业环节的运单数（AO002~AO010），用于作业成本最终分摊到每件运单
-- 结果写入 ABC_FCT_AO_DRIV
CALL p_abc_fct_ao_driv('2019-06-01 00:00:00');

-- ============================================================
-- 查询验证：检查动因数据是否正确生成
-- ============================================================

-- 查询动因逻辑配置，验证生效的动因规则
select * from ABC_REL_DRIV_LOGIC a where a.op_dt<'2019-06-01 00:00:00';

-- 查询 RR 动因（各机构的收派票数动因量）
select * from abc_fct_rr_driv;

-- 查询 RA 动因（线路里程、装卸中转票数等动因量）
select * from abc_fct_ra_driv;

-- 查询 AA 动因（装载重量、整包单件装卸/中转票数等动因量）
select * from abc_fct_aa_driv;

-- 查询 AO 动因（AO005=车辆运输的运单数），验证运输作业的运单动因量
select * from abc_fct_ao_driv a where a.driv_code='AO005';
