-- ============================================================
-- 文件名: 7.3-运行脚本.sql
-- 说明: 执行四级分摊的前半段（RR + RA），完成资源→资源、资源→作业的成本流转
--       1) RR 分摊：共享资源在功能中心间分摊（如营业点公共资源→收件/派件）
--       2) RA 分摊：资源成本分摊到作业（如薪酬→收件作业、运输费→支线/干线）
--       3) AA 分摊：辅助作业间相互分摊（如支线→支线正常/闲置）
--       4) AO 分摊：作业成本最终分摊到运单
-- 执行顺序: 第5步（前半段分摊），在动因执行（6.4）之后执行
-- ============================================================

-- MySQL 版本
-- 源文件: 7.3-运行脚本.sql
USE abc_blt;

-- 第1步：执行 RR 分摊（资源→资源）
-- 将营业点公共功能中心的资源（如经理室薪酬、公共设备折旧）
-- 按收派票数（RR002）分摊到收件、派件等功能中心
-- 结果写入 ABC_FCT_RR_DIST
CALL p_abc_fct_rr_dist('2019-06-01 00:00:00');

-- 第2步：执行 RA 分摊（资源→作业）
-- 将各功能中心的资源成本按动因分摊到具体作业
-- 直接记入（RA001）：如收件薪酬→收件作业
-- 按里程分摊（RA002）：如运输费→支线/干线作业
-- 按装卸中转票数（RA003）：如中转场公共费用→装卸/中转作业
-- 结果写入 ABC_FCT_RA_DIST
CALL p_abc_fct_ra_dist('2019-06-01 00:00:00');

-- 第3步：执行 AA 分摊（作业→作业）
-- 将辅助作业成本按动因细分到子作业
-- 按装载重量（AA002）：支线→支线正常/闲置，干线→干线正常/闲置
-- 按整包单件（AA003/AA004）：装卸→整包装卸/单件装卸，中转→整包中转/单件中转
-- 结果写入 ABC_FCT_AA_DIST
CALL p_abc_fct_aa_dist('2019-06-01 00:00:00');

-- 第4步：执行 AO 分摊（作业→运单）
-- 将每个作业的成本按运单数动因最终分摊到每件运单
-- 完成成本从资源到运单的四级流转
-- 结果写入 ABC_FCT_AO_DIST
CALL p_abc_fct_ao_dist('2019-06-01 00:00:00');
