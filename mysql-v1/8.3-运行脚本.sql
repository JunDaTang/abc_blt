-- ============================================================
-- 文件名: 8.3-运行脚本.sql
-- 说明: 执行四级分摊的后半段（AO 动因 + 四级分摊 + 分摊检测）
--       与 7.3 的区别：本脚本额外包含 AO 动因生成和分摊质量检测
--       1) 先生成 AO 动因（确保运单数动因是最新的）
--       2) 再依次执行四级分摊（RR → RA → AA → AO）
--       3) 最后执行分摊检测（检查未分摊的成本和异常数据）
-- 执行顺序: 第6步（后半段分摊），在动因执行（6.4）之后执行
-- ============================================================

-- MySQL 版本
-- 源文件: 8.3-运行脚本.sql
USE abc_blt;

-- 第1步：生成 AO 动因（作业→运单的运单数动因）
-- 重新计算各作业的运单数，确保 AO 分摊前动因数据最新
CALL p_abc_fct_ao_driv('2019-06-01 00:00:00');

-- 第2步：执行 RR 分摊（资源→资源）
-- 共享资源在功能中心间按动因分摊
CALL p_abc_fct_rr_dist('2019-06-01 00:00:00');

-- 第3步：执行 RA 分摊（资源→作业）
-- 资源成本按动因分摊到作业
CALL p_abc_fct_ra_dist('2019-06-01 00:00:00');

-- 第4步：执行 AA 分摊（作业→作业）
-- 辅助作业间按动因相互分摊
CALL p_abc_fct_aa_dist('2019-06-01 00:00:00');

-- 第5步：执行 AO 分摊（作业→运单）
-- 作业成本最终按运单数动因分摊到每件运单
CALL p_abc_fct_ao_dist('2019-06-01 00:00:00');

-- 第6步：执行分摊检测（检查分摊结果的完整性）
-- 检查是否有成本未被分摊（动因量为0或规则缺失的情况）
-- 结果写入 ABC_FCT_CHK_DIST（分摊检测表）
CALL p_abc_fct_check_dist('2019-06-01 00:00:00');

-- 第7步：生成未分摊清单
-- 列出所有未能成功分摊的成本项，便于排查规则缺失或数据异常
-- 结果写入 ABC_FCT_NO_DIST_LIST
CALL p_abc_fct_no_dist_list('2019-06-01 00:00:00');

-- ============================================================
-- 查询验证：检查分摊检测结果
-- ============================================================

-- 查询分摊检测表，检查是否有分摊异常（201905月份）
select * from abc_fct_chk_dist a where a.month_code='201905';

-- 查询未分摊清单，确认所有成本都已成功分摊到运单（201905月份）
select * from abc_fct_no_dist_list a where a.month_code='201905';
