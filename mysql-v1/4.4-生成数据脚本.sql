-- ============================================================
-- 文件名: 4.4-生成数据脚本.sql
-- 说明: 调用存储过程生成 ABC 系统所需的业务数据（随机模拟数据）
--       1) 生成机构维表（含层级关系）
--       2) 生成运单信息（随机模拟收派件数据）
--       3) 生成 ODS 科目余额（模拟财务数据）
--       4) 生成资源清单（各机构各功能的资源列表）
--       5) 生成业务量（运单的操作环节记录）
-- 执行顺序: 第2步（业务数据生成），在配置数据（3.2/4.2）之后、动因执行（6.4）之前执行
-- ============================================================

-- MySQL 版本
-- 源文件: 4.4-生成数据脚本.sql
USE abc_blt;

-- 第1步：生成机构维表（含层级关系，初始化模式）
-- 参数1='2019-05-01' 为数据日期，参数2=1 表示初始化（清空重建）
-- 基于 ODS_DEPT 源数据，构建 ABC_DIM_DEPT 维表
CALL p_abc_dim_dept('2019-05-01 00:00:00', 1);

-- 第2步：生成运单信息（随机模拟数据）
-- 参数1='2019-05-01' 为起始日期，参数2='2019-06-01' 为截止日期
-- 随机生成运单号、收发件信息、产品、客户、收入等，写入 ABC_BSL_WAYBILL
CALL p_abc_data_waybill('2019-05-01 00:00:00', '2019-06-01 00:00:00');

-- 第3步：生成 ODS 科目余额（模拟财务成本数据）
-- 参数='2019-05-01' 为月份（取月初日期）
-- 将科目余额数据写入 ODS_SUBJ_ACCO，金额基于运单收入按一定比例随机生成
CALL p_abc_data_subj_acco('2019-05-01 00:00:00');

-- 第4步：生成资源清单
-- 参数='2019-05-01' 为月份
-- 根据机构维表和各功能中心，生成 ABC_FCT_RESO_LIST（机构×功能×资源列表）
CALL p_abc_fct_reso_list('2019-05-01 00:00:00');

-- 第5步：生成业务量
-- 参数1='2019-05-01' 起始日期，参数2='2019-06-01' 截止日期
-- 根据运单数据生成 ABC_BSL_OP_WAYBILL（运单在各操作环节的业务量记录）
CALL p_abc_bsl_op_waybill('2019-05-01 00:00:00', '2019-06-01 00:00:00');

-- ============================================================
-- 查询验证：检查生成的数据是否正确
-- ============================================================

-- 查询 ODS 科目余额（201905月份），验证财务数据是否已生成
select * from ods_subj_acco a where a.month_code='201905';

-- 查询运单信息，验证运单数据是否已生成
select * from abc_bsl_waybill a where a.send_dt<'2019-06-01 00:00:00';

-- 查询资源清单（201905月份），验证机构×功能×资源组合是否完整
select * from abc_fct_reso_list a where a.month_code='201905';

-- 查询业务量，验证运单操作环节记录是否已生成
select * from abc_bsl_op_waybill;
